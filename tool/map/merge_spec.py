# 그때 근거 중 하나가 정확히 "독도는 현재 에셋에 존재하지 않으며" 였다.
# 다만 그때 검토한 것은 울릉도를 울릉군에서 **떼는** 안이었고 이번은 **추가**다.
#
# 원본 `sgg_simplified.geojson` 에도 독도가 없다 (울릉군은 폴리곤 1개·정점 23개,
# 130.79~130.92°E 본섬만). 그래서 **경위도를 투영하는 것이 아니라 모양과 위치를
# 직접 준다.** 실제 0.187km² 는 전국 뷰에서 약 0.5px 라 어차피 그릴 수 없다.
#
# ## 크기와 위치를 이렇게 정한 이유
#
# 크기: 폭 **8km**. 사용자가 고른 기준은 "전국 뷰에서 약 6px" 였는데, 처음 잡은
# 5km 는 **실기기에서 약 3.3px 밖에 안 됐다** — 지도 폭이 화면 폭(360 logical px)에
# 맞춰지므로 1km 가 약 0.74px 다. 6px 를 실제로 얻으려면 8km 가 필요하다.
# 울릉도 폭이 약 11.4km 라 70% 수준이며 위계는 유지된다.
#
# **화면 폭에 따라 달라지는 값이다.** 더 좁은 기기에서는 더 작게 보인다.
#
# 위치: **오른쪽 끝을 울릉군 오른쪽 끝에 맞추고 아래로 3km 띄운다.**
# 지도 프레임은 긁기 단위 좌표에서 계산되므로(`make_asset.py`), 울릉군보다 더
# 오른쪽에 놓으면 **지도 폭이 늘어 남한 전체가 화면에서 작아진다.** 전국 뷰
# 최소 지역이 이미 약 2px 라 그 대가가 크다. 오른쪽 끝을 맞추면 **W·H 가 한 톨도
# 바뀌지 않으면서** 울릉도의 오른쪽 아래라는 방향은 유지된다.
#
# 실제 독도는 울릉도 동남쪽 87.4km 다. 울릉군 자체를 이미 동해 안쪽으로 95km
# 당겨 놓았으므로(`OFFSET`), 여기서도 방향만 지키고 거리는 압축한다.
