def dokdo_rings(anchor_bounds):
    """울릉군 bounds `(x0, y0, x1, y1)` 를 받아 독도 링을 평면 좌표로 만든다.

    좌표계는 `make_asset.py` 의 투영 결과와 같다 (km, y 는 아래로 증가).
    """
    pts = [p for ring in DOKDO['rings'] for p in ring]
    sx0 = min(x for x, _ in pts)
    sx1 = max(x for x, _ in pts)
    sy0 = min(y for _, y in pts)
    k = DOKDO['width_km'] / (sx1 - sx0)
    # 오른쪽 끝 정렬 + 아래로 띄우기.
    ax0, ay0, ax1, ay1 = anchor_bounds
    dx = ax1 - DOKDO['width_km'] - sx0 * k
    dy = ay1 + DOKDO['gap_below_km'] - sy0 * k

    # **첫 정점을 끝에 반복해 링을 닫는다.**
    #
    # 원본 GeoJSON 링은 전부 닫혀 있고, 앱의 `Region.distanceTo()` 는 연속한
    # 정점 쌍만 훑으므로 **닫지 않으면 마지막→첫 정점 변이 거리 계산에서 빠진다.**
    # 그러면 그 변 바로 위의 점조차 0.47km 떨어진 것으로 나와, 가뜩이나 작은
    # 독도의 탭 허용 오차가 한쪽만 사라진다 (Codex 14회차 지적, 재현 확인).
    out = []
    for ring in DOKDO['rings']:
        pts = [(x * k + dx, y * k + dy) for x, y in ring]
        out.append(pts + [pts[0]])
    return out


def unit_for(sidonm, sgg, sggnm, unit):
    """이 피처가 될 긁기 단위의 (코드, 이름).

    **판정은 `unit` 으로 한다.** mapshaper 가 `-dissolve2 unit` 으로 묶은 키라
    그 피처가 어느 그룹에 들어갔는지를 그것만이 말해 준다. 병합 피처의
    `sgg`·`sggnm` 은 합쳐진 것 중 **아무거나 하나**라 믿을 수 없다.

    예전에는 `sggnm` 이 제외 대상인지로 판정했다. 정상 병합에서는 맞았지만
    **검증해야 할 것은 비정상 병합이라 뜻이 없었다** — 병합 피처가 대표 속성으로
    강화군을 물고 도심 한 곳이 잘못 잔류하면, 앞뒤가 뒤바뀐 채로 최종 코드
    집합이 그대로 `{28000, 28710, 28720}` 이 되어 검사를 통과했다.
    (Codex 30회차 코드 리뷰 지적, 반례를 재현해 확인함)
    """
    m = MERGE.get(sidonm)
    if m is None or unit != sidonm:
        return (sgg, sggnm)
    return (m['code'], m['name'])


def expected_codes(sidonm, residual):
    """병합 대상 시도의 **최종 코드 집합**. 명세만으로 만든다.

    [residual] 은 그 시도에서 **병합되지 않고 잔류한** `{이름: sgg}` 다.
    검사만 하고 **기대값에는 쓰지 않는다** — 검증 대상을 정답으로 삼으면
    함께 틀어져 통과한다.
    """
    m = MERGE[sidonm]
    exclude = m.get('exclude', {})
    for name, code in exclude.items():
        if name not in residual:
            raise SystemExit(
                '%s 의 %s 가 잔류하지 않았다 — 병합에 딸려 들어갔다. '
                'mapshaper 표현식의 제외 조건을 확인한다.' % (sidonm, name))
        if residual[name] != code:
            raise SystemExit(
                '%s 의 %s 코드가 %s 다. 명세는 %s.'
                % (sidonm, name, residual[name], code))
    extra = set(residual) - set(exclude)
    if extra:
        raise SystemExit(
            '%s 에 병합되지 않고 남은 곳이 있다: %s' % (sidonm, sorted(extra)))
    return {m['code']} | set(exclude.values())


def is_merged(code):
    return code in MERGED_CODES
