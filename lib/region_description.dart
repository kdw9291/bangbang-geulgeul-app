/// 미수집 팝업에 이 값이 새면 "가리고 긁을 때 공개" 결정이 깨진다.
String descriptionFor(String scratchUnitId) {
  final landmark = kLandmarkDescription[scratchUnitId];
  if (landmark != null) return landmark;
  final cat = kRegionCategory[scratchUnitId];
  return cat == null ? '' : kCategoryPhrase[cat] ?? '';
}
